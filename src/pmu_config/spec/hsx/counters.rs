//! 7ab0b6e2c09d3df26671c7875148d6ab6e853775, BDX/events/broadwellx_uncore.json
//! (V23): the union of the `Counter` fields of all events of a `Unit` and
//! `EventCode`. HSX/events/haswellx_uncore.json (V29) gives the same masks for
//! these units. The iMC fixed counter (`Counter` "FIXED", UNC_M_CLOCKTICKS) is
//! not a general counter. Linux's `bdx_uncore_cbox_constraints` agrees; its
//! Haswell-EP table keeps CBo event 0x09 on counter 0, where the JSON and the
//! Haswell-EP uncore guide (331051) allow counters 0-1.

