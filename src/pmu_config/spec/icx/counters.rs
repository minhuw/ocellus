//! uncore event code counts on, as a mask (bit n: counter n), sorted by event
//! code.
//!
//! Source: Intel perfmon (https://github.com/intel/perfmon)
//! ICX/events/icelakex_uncore.json and icelakex_uncore_experimental.json
//! (V1.30), SPR/events/sapphirerapids_uncore.json and
//! sapphirerapids_uncore_experimental.json (V1.39), and the EMR files
//! (V1.23): the union of the `Counter` fields of all `CounterType` "PGMABLE"
//! events of a `Unit` and `EventCode`. The Emerald Rapids tables equal the
//! Sapphire Rapids ones, so `SPR_*` serves both. Fixed and free-running
//! counters (the ICX iMC UNC_M_HCLOCKTICKS, the IIO and iMC *_FREERUN events)
//! are not general counters.

